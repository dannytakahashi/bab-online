/**
 * Assembles the socket contract from defs.js, c2s.js and s2c.js. gen.js
 * writes the result to contract/events.schema.json (the artifact other
 * consumers read, e.g. a future Swift Codable generator).
 */

'use strict';

const { defs } = require('./defs');
const { c2s } = require('./c2s');
const { s2c } = require('./s2c');

const SNAPSHOT_VERSION = 2;

function buildSchema() {
    return {
        $schema: 'https://json-schema.org/draft/2020-12/schema',
        title: 'BAB Online socket contract',
        snapshotVersion: SNAPSHOT_VERSION,
        $comment: 'GENERATED by npm run contract:gen from contract/src. Wire changes are additive only until the v1 removals (contract/V1_REMOVALS.md).',
        $defs: defs,
        c2s,
        s2c,
        builtins: {
            c2s: ['disconnect'],
            s2c: ['connect', 'disconnect', 'reconnect_attempt', 'reconnect_failed'],
        },
    };
}

module.exports = { buildSchema, SNAPSHOT_VERSION };
