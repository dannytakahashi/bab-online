/**
 * Design token generator (roadmap item 18a): tokens.json -> CSS custom
 * properties (client/styles/tokens.css) and an ES module of numbers and
 * hex values for Phaser (client/src/ui/tokens.js). Pure functions, so the
 * stale-file test (tokens.test.js) and scripts/build-tokens.js share them.
 * Item 29 adds a Theme.swift writer beside these two.
 */

/** camelCase -> kebab-case. */
const kebab = (s) => String(s).replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

/** surface.s0 -> surface-0, space.s4 -> space-4: the s prefix only makes a JSON key of a number. */
const keyPart = (k) => (/^s\d+$/.test(k) ? k.slice(1) : kebab(k));

/** Parse #RGB, #RRGGBB or #RRGGBBAA into {r, g, b, a} (a in 0..1). */
export function parseColor(hex) {
  let h = String(hex).trim().replace(/^#/, '');
  if (h.length === 3) h = h.split('').map((c) => c + c).join('');
  if (!/^[0-9a-fA-F]{6}([0-9a-fA-F]{2})?$/.test(h)) throw new Error(`bad color ${hex}`);
  const n = (i) => parseInt(h.slice(i, i + 2), 16);
  return { r: n(0), g: n(2), b: n(4), a: h.length === 8 ? Math.round((n(6) / 255) * 1000) / 1000 : 1 };
}

/** Every color token as [path[], value] (path below `color`). */
export function colorEntries(tokens) {
  const out = [];
  const walk = (node, path) => {
    if (typeof node === 'string') { out.push([path, node]); return; }
    for (const [k, v] of Object.entries(node)) walk(v, [...path, k]);
  };
  walk(tokens.color, []);
  return out;
}

/** A color token by dotted path ('surface.s2'); 'path@0.86' overrides its alpha. */
export function resolveColor(tokens, ref) {
  const [path, alpha] = String(ref).split('@');
  let node = tokens.color;
  for (const k of path.split('.')) node = node?.[k];
  if (typeof node !== 'string') throw new Error(`unknown color token ${path}`);
  const c = parseColor(node);
  if (alpha !== undefined) c.a = Number(alpha);
  return c;
}

/** Composite a stack of colors, top first, over an opaque bottom. */
export function composite(colors) {
  const stack = [...colors].reverse();
  let base = { ...stack[0], a: 1 };
  for (const c of stack.slice(1)) {
    base = {
      r: c.r * c.a + base.r * (1 - c.a),
      g: c.g * c.a + base.g * (1 - c.a),
      b: c.b * c.a + base.b * (1 - c.a),
      a: 1,
    };
  }
  return base;
}

/** WCAG 2.x relative luminance. */
export function luminance({ r, g, b }) {
  const ch = (v) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b);
}

/** WCAG contrast ratio of fg (composited over bg) on bg. */
export function contrastRatio(fg, bg) {
  const f = fg.a < 1 ? composite([fg, bg]) : fg;
  const L1 = luminance(f);
  const L2 = luminance(bg);
  const [hi, lo] = L1 > L2 ? [L1, L2] : [L2, L1];
  return (hi + 0.05) / (lo + 0.05);
}

/** Every contrast pair of tokens.json with its measured ratio. */
export function contrastReport(tokens) {
  return tokens.contrast.map((p) => {
    const bg = composite(p.bg.map((ref) => resolveColor(tokens, ref)));
    const fg = resolveColor(tokens, p.fg);
    const ratio = contrastRatio(fg, bg);
    return { ...p, ratio: Math.round(ratio * 100) / 100, ok: ratio + 1e-9 >= p.min };
  });
}

const cssColor = (hex) => {
  const { r, g, b, a } = parseColor(hex);
  return a < 1 ? `rgb(${r} ${g} ${b} / ${a})` : String(hex).toLowerCase();
};

const shadowCss = (layers) => layers.map((l) => {
  const { r, g, b, a } = parseColor(l.color);
  return `${l.x}px ${l.y}px ${l.blur}px ${l.spread}px rgb(${r} ${g} ${b} / ${a})`;
}).join(', ');

const bezier = (p) => `cubic-bezier(${p.join(', ')})`;

const fontStack = (list) => list.map((f) => (/[\s]/.test(f) ? `"${f}"` : f)).join(', ');

const HEADER = (what) => `Generated by scripts/build-tokens.js from client/tokens/tokens.json (${what}). Do not edit: change tokens.json and run npm run tokens.`;

/** client/styles/tokens.css */
export function renderCss(tokens) {
  const lines = [];
  const add = (name, value) => lines.push(`    --${name}: ${value};`);
  for (const [path, value] of colorEntries(tokens)) {
    const name = path.map(keyPart).join('-');
    add(name, cssColor(value));
    const { r, g, b } = parseColor(value);
    add(`${name}-rgb`, `${r} ${g} ${b}`);
  }
  add('font-ui', fontStack(tokens.font.ui));
  for (const [k, v] of Object.entries(tokens.font.weight)) add(`weight-${kebab(k)}`, String(v));
  for (const [k, v] of Object.entries(tokens.type)) add(`type-${kebab(k)}`, `${v}px`);
  for (const [k, v] of Object.entries(tokens.space)) add(`space-${keyPart(k)}`, `${v}px`);
  for (const [k, v] of Object.entries(tokens.radius)) add(`radius-${kebab(k)}`, `${v}px`);
  for (const [k, v] of Object.entries(tokens.elevation)) add(`elev-${k.replace(/^e/, '')}`, shadowCss(v));
  for (const [k, v] of Object.entries(tokens.z)) add(`z-${kebab(k)}`, String(v));
  for (const [k, v] of Object.entries(tokens.motion.duration)) add(`dur-${kebab(k)}`, `${v}ms`);
  for (const [k, v] of Object.entries(tokens.motion.easing)) add(`ease-${kebab(k)}`, bezier(v));
  for (const [k, v] of Object.entries(tokens.motion.stagger)) add(`stagger-${kebab(k)}`, `${v}ms`);
  add('glow-period', `${tokens.motion.glowPeriod}ms`);
  add('hit-target', `${tokens.hitTarget}px`);
  return [
    `/* ${HEADER('CSS custom properties')} */`,
    ':root {',
    ...lines,
    '}',
    '',
    '/* Reduced motion: cosmetic durations collapse (kit.css and table.css read them) */',
    '@media (prefers-reduced-motion: reduce) {',
    '    :root {',
    ...Object.keys(tokens.motion.duration).map((k) => `        --dur-${kebab(k)}: 0ms;`),
    ...Object.keys(tokens.motion.stagger).map((k) => `        --stagger-${kebab(k)}: 0ms;`),
    '    }',
    '}',
    '',
  ].join('\n');
}

const js = (v) => JSON.stringify(v, null, 2);

/** client/src/ui/tokens.js */
export function renderJs(tokens) {
  const color = JSON.parse(JSON.stringify(tokens.color));
  const motion = {
    fast: tokens.motion.duration.fast,
    base: tokens.motion.duration.base,
    slow: tokens.motion.duration.slow,
    dealStagger: tokens.motion.stagger.deal,
    glowPeriod: tokens.motion.glowPeriod,
    easing: { ...tokens.motion.easing },
  };
  return [
    `// ${HEADER('ES module for Phaser and the DOM')}`,
    '',
    '/** Colors as #RRGGBB / #RRGGBBAA strings (hex() and alpha() turn them into Phaser values). */',
    `export const COLOR = Object.freeze(${js(color)});`,
    '',
    `export const FONT_UI = ${JSON.stringify(fontStack(tokens.font.ui))};`,
    `export const WEIGHT = Object.freeze(${js(tokens.font.weight)});`,
    `export const TYPE = Object.freeze(${js(tokens.type)});`,
    `export const SPACE = Object.freeze(${js(tokens.space)});`,
    `export const RADIUS = Object.freeze(${js(tokens.radius)});`,
    `export const Z = Object.freeze(${js(tokens.z)});`,
    '/** Durations in ms; easing as cubic-bezier control points. */',
    `export const MOTION = Object.freeze(${js(motion)});`,
    `export const HIT_TARGET = ${tokens.hitTarget};`,
    '',
    '/** A token color as a Phaser number (0xRRGGBB). */',
    'export function hex(color) {',
    "  return parseInt(String(color).replace('#', '').slice(0, 6), 16);",
    '}',
    '',
    '/** A token color\'s alpha (1 unless #RRGGBBAA). */',
    'export function alpha(color) {',
    "  const h = String(color).replace('#', '');",
    '  return h.length === 8 ? Math.round((parseInt(h.slice(6), 16) / 255) * 1000) / 1000 : 1;',
    '}',
    '',
  ].join('\n');
}

/** Both outputs, keyed by their path from the repo root. */
export function renderAll(tokens) {
  return {
    'client/styles/tokens.css': renderCss(tokens),
    'client/src/ui/tokens.js': renderJs(tokens),
  };
}
